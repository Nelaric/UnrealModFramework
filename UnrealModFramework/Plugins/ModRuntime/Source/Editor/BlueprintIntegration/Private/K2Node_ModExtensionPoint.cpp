UScriptStruct* GetStruct(const UModBlueprintExportEntry* Entry)
{
	if (const auto* Hook = Cast<UModBlueprintHookExport>(Entry))
	{
		return Hook->ContextType;
	}
	const auto* Event = Cast<UModBlueprintEventExport>(Entry);
	return Event ? Event->PayloadType.Get() : nullptr;
}

UClass* GetObjectClass(const UModBlueprintExportEntry* Entry)
{
	if (const auto* Hook = Cast<UModBlueprintHookExport>(Entry))
	{
		return Hook->ObjectType.Get();
	}
	const auto* Event = Cast<UModBlueprintEventExport>(Entry);
	return Event ? Event->ObjectType.Get() : nullptr;
}

EModBlueprintExtensionScalar GetScalar(const UModBlueprintExportEntry* Entry)
{
	if (const auto* Hook = Cast<UModBlueprintHookExport>(Entry))
	{
		return Hook->Scalar;
	}
	const auto* Event = Cast<UModBlueprintEventExport>(Entry);
	return Event ? Event->Scalar : EModBlueprintExtensionScalar::Float;
}

UFunction* FindRuntimeEntry(bool bHook, EModBlueprintExtensionScalar Scalar)
{
	static const FName Hooks[]{GET_FUNCTION_NAME_CHECKED(UModHostExtensionLibrary, HookPoint),
	                           GET_FUNCTION_NAME_CHECKED(UModHostExtensionLibrary, HookPointDouble),
	                           GET_FUNCTION_NAME_CHECKED(UModHostExtensionLibrary, HookPointInt32),
	                           GET_FUNCTION_NAME_CHECKED(UModHostExtensionLibrary, HookPointInt64),
	                           GET_FUNCTION_NAME_CHECKED(UModHostExtensionLibrary, HookPointBool),
	                           GET_FUNCTION_NAME_CHECKED(UModHostExtensionLibrary, HookPointByte)};
	static const FName Events[]{GET_FUNCTION_NAME_CHECKED(UModHostExtensionLibrary, PublishEvent),
	                            GET_FUNCTION_NAME_CHECKED(UModHostExtensionLibrary, PublishEventDouble),
	                            GET_FUNCTION_NAME_CHECKED(UModHostExtensionLibrary, PublishEventInt32),
	                            GET_FUNCTION_NAME_CHECKED(UModHostExtensionLibrary, PublishEventInt64),
	                            GET_FUNCTION_NAME_CHECKED(UModHostExtensionLibrary, PublishEventBool),
	                            GET_FUNCTION_NAME_CHECKED(UModHostExtensionLibrary, PublishEventByte)};
	const int32 Index = static_cast<uint8>(Scalar);
	return Index < UE_ARRAY_COUNT(Hooks)
	           ? UModHostExtensionLibrary::StaticClass()->FindFunctionByName(bHook ? Hooks[Index] : Events[Index])
	           : nullptr;
}
