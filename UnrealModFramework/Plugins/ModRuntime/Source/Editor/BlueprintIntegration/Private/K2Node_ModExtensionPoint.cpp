void UK2Node_ModExtensionPoint::AllocateDefaultPins()
{
	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Execute);
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Then);
	auto* Value = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Real, UEdGraphSchema_K2::PC_Float, TEXT("Value"));
	GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValueBasedOnType(Value);
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Int, UEdGraphSchema_K2::PN_ReturnValue);
	if (bHook)
	{
		CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Real, UEdGraphSchema_K2::PC_Float, TEXT("Result"));
		CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Boolean, TEXT("bCancelled"));
		CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Boolean, TEXT("bCommitted"));
	}
}

const UModBlueprintExportEntry* UK2Node_ModExtensionPoint::FindDeclaration(const UBlueprint& Blueprint) const
{
	const auto* Exports = UModBlueprintExports::Find(&Blueprint);
	if (Exports && Declaration.IsValid())
	{
		if (bHook)
		{
			for (const UModBlueprintHookExport* Entry : Exports->Hooks)
			{
				if (Entry && Entry->EntryGuid == Declaration)
				{
					return Entry;
				}
			}
		}
		else
		{
			for (const UModBlueprintEventExport* Entry : Exports->Events)
			{
				if (Entry && Entry->EntryGuid == Declaration)
				{
					return Entry;
				}
			}
		}
	}
	return nullptr;
}

FText UK2Node_ModExtensionPoint::GetNodeTitle(ENodeTitleType::Type TitleType) const
{
	if (const UBlueprint* Blueprint = GetBlueprint())
	{
		if (const auto* Entry = FindDeclaration(*Blueprint))
		{
			return FText::Format(bHook ? LOCTEXT("Hook", "Hook Point {0}") : LOCTEXT("Event", "Publish Event {0}"),
			                     Entry->GetExportDisplayName());
		}
	}
	return bHook ? LOCTEXT("MissingHook", "Hook Point") : LOCTEXT("MissingEvent", "Publish Event");
}

FText UK2Node_ModExtensionPoint::GetMenuCategory() const
{
	return LOCTEXT("Category", "Mod|Extension");
}

void UK2Node_ModExtensionPoint::GetMenuActions(FBlueprintActionDatabaseRegistrar& Registrar) const
{
	const auto* Blueprint = Cast<UBlueprint>(Registrar.GetActionKeyFilter());
	const auto* Exports = Blueprint ? UModBlueprintExports::Find(Blueprint) : nullptr;
	if (!Exports)
	{
		return;
	}
	const auto Add = [&](const UModBlueprintExportEntry& Entry, bool bForHook)
	{
		auto* Spawner = UBlueprintNodeSpawner::Create(GetClass());
		Spawner->DefaultMenuSignature.MenuName = FText::Format(bForHook ? LOCTEXT("HookAction", "Hook Point {0}")
		                                                                : LOCTEXT("EventAction", "Publish Event {0}"),
		                                                       Entry.GetExportDisplayName());
		Spawner->DefaultMenuSignature.Category = GetMenuCategory();
		Spawner->CustomizeNodeDelegate = UBlueprintNodeSpawner::FCustomizeNodeDelegate::CreateLambda(
		    [Guid = Entry.EntryGuid, bForHook](UEdGraphNode* Node, bool)
		    {
			    auto* Point = CastChecked<UK2Node_ModExtensionPoint>(Node);
			    Point->Declaration = Guid;
			    Point->bHook = bForHook;
		    });
		Registrar.AddBlueprintAction(Blueprint, Spawner);
	};
	for (const UModBlueprintHookExport* Entry : Exports->Hooks)
	{
		if (Entry)
		{
			Add(*Entry, true);
		}
	}
	for (const UModBlueprintEventExport* Entry : Exports->Events)
	{
		if (Entry && Entry->bScalarPayload)
		{
			Add(*Entry, false);
		}
	}
}

bool UK2Node_ModExtensionPoint::IsCompatibleWithGraph(const UEdGraph* Graph) const
{
	return Super::IsCompatibleWithGraph(Graph) && Graph->GetSchema()->GetGraphType(Graph) != GT_Macro;
}

void UK2Node_ModExtensionPoint::ExpandNode(FKismetCompilerContext& Compiler, UEdGraph* Graph)
{
	Super::ExpandNode(Compiler, Graph);
	const UBlueprint* Blueprint = Compiler.Blueprint;
	const auto* Entry = Blueprint ? FindDeclaration(*Blueprint) : nullptr;
	const auto* Event = Cast<UModBlueprintEventExport>(Entry);
	if (!Entry || (Event && !Event->bScalarPayload))
	{
		Compiler.MessageLog.Error(
		    *LOCTEXT("InvalidDeclaration", "@@ has an invalid Mod extension declaration.").ToString(), this);
		BreakAllNodeLinks();
		return;
	}
	auto* Call = Compiler.SpawnIntermediateNode<UK2Node_CallFunction>(this, Graph);
	static const FName HookName = GET_FUNCTION_NAME_CHECKED(UModHostExtensionLibrary, HookPoint);
	static const FName EventName = GET_FUNCTION_NAME_CHECKED(UModHostExtensionLibrary, PublishEvent);
	UFunction* Target = UModHostExtensionLibrary::StaticClass()->FindFunctionByName(bHook ? HookName : EventName);
	if (!Target)
	{
		Compiler.MessageLog.Error(*LOCTEXT("MissingEntry", "@@ cannot find its runtime extension entry.").ToString(),
		                          this);
		BreakAllNodeLinks();
		return;
	}
	Call->SetFromFunction(Target);
	Call->AllocateDefaultPins();
	Call->FindPinChecked(TEXT("Id"))->DefaultValue = Declaration.ToString(EGuidFormats::Digits).ToLower();
	for (UEdGraphPin* Pin : Pins)
	{
		UEdGraphPin* Destination = Call->FindPin(Pin->PinName, Pin->Direction);
		if (!Destination)
		{
			Compiler.MessageLog.Error(
			    *LOCTEXT("MissingPin", "@@ does not match the runtime extension entry.").ToString(), this);
			break;
		}
		Compiler.MovePinLinksToIntermediate(*Pin, *Destination);
	}
	BreakAllNodeLinks();
}

