#include "HostLinkHeader.h"

#include "Common/Files/File.h"
#include "Common/Files/Path.h"

#include <algorithm>
#include <filesystem>
#include <stdexcept>
#include <string>

namespace Mod::SourceTool
{
namespace fs = std::filesystem;

void HostLinkHeader::GenerateHostLink(const std::string& Owner, const std::string& Destination)
{
	const auto IsIdentifierStart = [](char Character)
	{ return (Character >= 'A' && Character <= 'Z') || (Character >= 'a' && Character <= 'z') || Character == '_'; };
	if (Owner.empty() || !IsIdentifierStart(Owner.front()) ||
	    !std::all_of(Owner.begin() + 1, Owner.end(), [&](char Character)
	                 { return IsIdentifierStart(Character) || (Character >= '0' && Character <= '9'); }))
	{
		throw std::runtime_error("Invalid host owner module name: " + Owner);
	}
	const auto Output = Mod::BuildTool::Path::ResolvePath({}, Destination);
	const std::string Header = "// Copyright (c) 2026 Nelaric Contributors\r\n"
	                           "// Generated by ModSourceTool.\r\n"
	                           "#pragma once\r\n"
	                           "#pragma comment(linker, \"/include:UMF_ModHost_" +
	                           Owner + "\")\r\n";
	if (!fs::is_regular_file(Output) || Mod::BuildTool::File::ReadFile(Output) != Header)
	{
		Mod::BuildTool::File::WriteFileAtomically(Output, Header);
	}
}
} // namespace Mod::SourceTool
