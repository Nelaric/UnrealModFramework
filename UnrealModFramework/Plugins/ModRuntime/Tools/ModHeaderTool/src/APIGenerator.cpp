void Emit(FGenerationModel Model, const fs::path& OutputDirectory)
{
	FJson Exports = FJson::array(), Types = FJson::array(), Sources = FJson::array();
	for (auto& [Name, Type] : Model.Types)
	{
		FJson Members = FJson::array();
		std::set<std::string> Shapes;
		for (auto Index : Type.APIs)
		{
			const auto& API = Model.APIs[Index];
			std::string Shape = API.ExportName + "(" + Parameters(API) + ")" + (API.bConst ? " const" : "");
			if (!Shapes.insert(Shape).second)
			{
				throw std::runtime_error("Projected overload collision: " + Name + "::" + Shape);
			}
			auto Member = APIJson(Model, API);
			Member.erase("metadata");
			Members.push_back(std::move(Member));
		}
		FJson TypeContract{
		    {"typeId", Type.Identity.Id}, {"scope", Type.Identity.Scope}, {"apis", Members}, {"projectionVersion", 1}};
		if (Type.bFullView)
		{
			TypeContract["view"] = "Full";
		}
		if (Type.bAllowWorldless)
		{
			TypeContract["allowWorldless"] = true;
		}
		Type.Signature = HashBytes(TypeContract.dump());
		TypeContract.erase("apis");
		TypeContract.erase("projectionVersion");
		TypeContract["cppName"] = Name;
		TypeContract["callingTableHash"] = Type.Signature;
		Types.push_back(std::move(TypeContract));
	}
	for (const auto& API : Model.APIs)
	{
		Exports.push_back(APIJson(Model, API));
		Sources.push_back({{"exportId", API.Id},
		                   {"module", API.Module},
		                   {"sourceSignature", API.SourceSignature},
		                   {"file", NormalizeInput(Model.Input, PathToUtf8(API.Macro.File))},
		                   {"line", API.Macro.Line},
		                   {"column", API.Macro.Column}});
	}
	FJson Contract{{"schemaVersion", 1},
	               {"projectionVersion", 1},
	               {"gameId", Model.Input.GameId},
	               {"objectReturnPolicy", "ErrorIfNull"},
	               {"types", Types},
	               {"exports", Exports}};
	std::string LifecycleExport;
	FJson Lifecycle;
	if (!Model.LifecycleSource.empty())
	{
		LifecycleExport = ExportLifecycleDeclarations(Model.LifecycleSource);
		Lifecycle = {{"schemaVersion", 1},
		             {"module", "ModLoader"},
		             {"resource", LifecyclePath},
		             {"resourceHash", HashBytes(LifecycleExport)}};
		Contract["modLifecycle"] = Lifecycle;
	}
	FJson Compatibility = Contract;
	for (auto& API : Compatibility["exports"])
	{
		API.erase("metadata");
	}
	const std::string ContractHash = HashBytes(Compatibility.dump());
	const std::string ProjectionHash = HashBytes(Types.dump() + "UObjectAPIProjection1:ContextHandlesV1" +
	                                             (Lifecycle.is_null() ? "" : Lifecycle.dump()));
	FFiles Files;
	WriteSdk(Model, Files);
	WriteHost(Model, Files);
	const FJson NativeABI = WriteNativeABI(Model, Files, ContractHash, ProjectionHash, Lifecycle);
	for (auto& [Path, Text] : Files)
	{
		if (Path.ends_with(".h") || Path.ends_with(".cpp"))
		{
			Text = SourceBytes(Text);
		}
	}
	if (!Lifecycle.is_null())
	{
		Files[LifecyclePath] = std::move(LifecycleExport);
	}
	Files["Contract/" + Model.Input.GameId + ".modcontract.json"] = Contract.dump(2) + '\n';
	Files["Diagnostics/" + Model.Input.GameId + ".sources.json"] = Sources.dump(2) + '\n';
	FJson Dependencies = FJson::array(), InputFiles = FJson::array();
	for (const auto& File : Model.Dependencies)
	{
		const auto Digest = fs::exists(File) ? HashFile(File) : std::string();
		const auto Leaf = PathToUtf8(File.filename());
		const bool ContextFile = File.extension() == ".rsp" || Leaf.starts_with("Definitions.") ||
		                         Leaf.starts_with("SharedDefinitions.") || Leaf.starts_with("SharedPCH.");
		Dependencies.push_back({{"path", NormalizeInput(Model.Input, PathToUtf8(File))}, {"contentHash", Digest}});
		InputFiles.push_back({{"path", PathToUtf8(File)},
		                      {"contentHash", Digest},
		                      {"kind", ContextFile ? "AnalysisContext" : "Semantic"}});
	}
	const auto ContextHash = HashBytes(FJson{
	    {"target", Model.Input.Target},
	    {"platform", Model.Input.Platform},
	    {"configuration", Model.Input.Configuration},
	    {"architecture", Model.Input.Architecture},
	    {"commands", Model.Commands},
	    {"clang", Model.ClangVersion},
	    {"macros", Model.ContextMacros}}.dump());
	const auto InputHash = HashBytes(Dependencies.dump() + ContextHash);
	std::string OutputHashes;
	for (const auto& [Path, Bytes] : Files)
	{
		OutputHashes += Path + ":" + HashBytes(Bytes) + "\n";
	}
	const auto GenerationId = HashBytes(InputHash + ContractHash + GeneratorVersion + OutputHashes);
	FJson Generated = FJson::array(), CompilationUnits = FJson::array(), HostContexts = FJson::object();
	for (const auto& [Path, Bytes] : Files)
	{
		const bool Host = Path.starts_with("Host/");
		const bool Implementation = Path.ends_with(".cpp");
		std::string Owner;
		if (Host)
		{
			Owner = Path.substr(5, Path.find('/', 5) - 5);
		}
		else if (Path.starts_with("Client/"))
		{
			Owner = Path.substr(7, Path.find('/', 7) - 7);
		}
		else if (Implementation)
		{
			Owner = Path.substr(12, Path.find(".modviews.cpp") - 12);
		}
		Generated.push_back(
		    {{"path", Path},
		     {"ownerModule", Owner.empty() ? FJson(nullptr) : FJson(Owner)},
		     {"role", Implementation ? (Path.ends_with(".modverify.cpp") ? "CompileVerification" : "HostBinding")
		              : Host         ? "HostHeader"
		              : Path == LifecyclePath         ? "SdkResource"
		              : Path.ends_with(".modabi.h")   ? "SdkHeader"
		              : Path.starts_with("SDK/")      ? "HostHeader"
		              : Path.starts_with("Contract/") ? "Contract"
		                                              : "Diagnostic"},
		     {"contentHash", HashBytes(Bytes)}});
		if (Implementation)
		{
			CompilationUnits.push_back({{"ownerModule", Owner}, {"source", Path}});
		}
	}
	for (const auto& [Owner, File] : Model.Input.HostContexts)
	{
		const auto Context = FJson::parse(ReadTextFile(File));
		if (Context.value("format", "") != "UMF.ModHostContext" || Context.value("schemaVersion", 0) != 2 ||
		    Context.value("ownerModule", "") != Owner || Context.value("moduleAPIMode", "") != "Producer" ||
		    Context.at("target").value("name", "") != Model.Input.Target ||
		    Context.at("target").value("platform", "") != Model.Input.Platform ||
		    Context.at("target").value("architecture", "") != Model.Input.Architecture ||
		    Context.at("target").value("configuration", "") != Model.Input.Configuration)
		{
			throw std::runtime_error("MBT host context does not match this module and Target: " + Owner);
		}
		HostContexts[Owner] = HashBytes(Context.dump());
	}

	FJson ConfigWatches = FJson::array();
	for (const auto& Root : Model.ConfigRoots)
	{
		std::set<std::string> Names;
		for (const auto& File : Tools::CollectConfigFiles(Root))
		{
			Names.insert(PathToUtf8(File));
		}
		ConfigWatches.push_back({{"root", PathToUtf8(Root)}, {"kind", "Config"}, {"files", Names}});
	}
	for (const auto& Module : Model.Input.Modules)
	{
		FProject Scoped = Model.Input.Project;
		Scoped.Directories = {Module.Root};
		std::set<std::string> Names;
		for (const auto& File : CollectSourceFiles(Scoped))
		{
			Names.insert(PathToUtf8(File));
		}
		ConfigWatches.push_back({{"root", PathToUtf8(Module.Root)}, {"kind", "Source"}, {"files", Names}});
	}
	const FJson Manifest{{"schemaVersion", 3},
	                     {"generatorVersion", GeneratorVersion},
	                     {"format", "UMF.GeneratedArtifacts"},
	                     {"outputLayout", "Flat"},
	                     {"backend", "UObjectAPI.Win64.v1"},
	                     {"gameId", Model.Input.GameId},
	                     {"target", Model.Input.Target},
	                     {"platform", Model.Input.Platform},
	                     {"configuration", Model.Input.Configuration},
	                     {"architecture", Model.Input.Architecture},
	                     {"generationId", GenerationId},
	                     {"status", "Complete"},
	                     {"inputHash", InputHash},
	                     {"buildContextHash", ContextHash},
	                     {"contractHash", ContractHash},
	                     {"projectionHash", ProjectionHash},
	                     {"nativeABIHash", NativeABI.at("nativeABIHash")},
	                     {"independentNativeABI", true},
	                     {"clientABI", NativeABI},
	                     {"requiredSymbols", NativeABI.at("requiredSymbols")},
	                     {"unresolvedTypeCount", 0},
	                     {"generatedFiles", Generated},
	                     {"compilationUnits", CompilationUnits},
	                     {"hostBuildContexts", HostContexts},
	                     {"dependencies", Dependencies},
	                     {"inputFiles", InputFiles},
	                     {"watchedDirectories", ConfigWatches}};
	const std::string ManifestName = Model.Input.GameId + ".generated-artifacts.json";
	const std::string ManifestBytes = Manifest.dump(2) + '\n';
	const fs::path Root = fs::absolute(OutputDirectory).lexically_normal();
	for (const auto& Dependency : Model.Dependencies)
	{
		const auto Relative = Dependency.lexically_relative(Root);
		if (!Relative.empty() && *Relative.begin() != "..")
		{
			throw std::runtime_error("Generation output must not contain an input: " + PathToUtf8(Dependency));
		}
	}
	Files[ManifestName] = ManifestBytes;
	PublishGeneratedFiles(Root, Files, ManifestName);
	std::cout << PathToUtf8(Root / ManifestName) << '\n';
}

void Generate(const fs::path& BuildInput, const fs::path& OutputDirectory, const fs::path& Options,
              const fs::path& ClangLibrary, const fs::path& HostContexts, const fs::path& LifecycleSource)
{
	auto Input = LoadGenerationInput(BuildInput);
	if (HostContexts.empty())
	{
		throw std::runtime_error("Complete generation requires --host-contexts for all Host and Client producers.");
	}
	const auto ContextFile = fs::canonical(HostContexts);
	const auto ContextSet = FJson::parse(ReadTextFile(ContextFile));
	if (ContextSet.value("format", "") != "UMF.ModHostContextSet" || ContextSet.value("schemaVersion", 0) != 1)
	{
		throw std::runtime_error("Unsupported MBT host context set.");
	}
	std::set<std::string> Owners{Input.GameId + "ModClient"};
	for (const auto& Module : Input.Modules)
	{
		if (!Owners.insert(Module.Name).second)
		{
			throw std::runtime_error("The reserved Client producer conflicts with host module: " + Module.Name);
		}
	}
	const auto& Contexts = ContextSet.at("contexts");
	if (!Contexts.is_object())
	{
		throw std::runtime_error("MBT context set requires a contexts object keyed by owner.");
	}
	for (const auto& Owner : Owners)
	{
		if (!Contexts.contains(Owner))
		{
			throw std::runtime_error("MBT context set is missing producer: " + Owner);
		}
		Input.HostContexts.emplace(
		    Owner, fs::canonical(ContextFile.parent_path() / PathFromUtf8(Contexts.at(Owner).get<std::string>())));
	}
	if (Contexts.size() != Owners.size())
	{
		throw std::runtime_error("MBT context set contains producers outside this generation.");
	}
	// The UE adapter pins expanded arguments before UBT rewrites its response files.
	fs::path AnalysisDatabase = Input.Database;
	if (ContextSet.contains("analysisCompilationDatabase"))
	{
		const auto ReadPath = [&](const char* Key)
		{ return fs::canonical(ContextFile.parent_path() / PathFromUtf8(ContextSet.at(Key).get<std::string>())); };
		if (!fs::equivalent(Input.Database, ReadPath("sourceCompilationDatabase")))
		{
			throw std::runtime_error("The analysis snapshot belongs to a different compilation database.");
		}
		AnalysisDatabase = ReadPath("analysisCompilationDatabase");
		if (ContextSet.value("sourceCompilationDatabaseHash", "") != HashFile(Input.Database) ||
		    ContextSet.value("analysisCompilationDatabaseHash", "") != HashFile(AnalysisDatabase))
		{
			throw std::runtime_error("The pinned compilation database changed. Refresh the producer context set.");
		}
	}
	auto Model = Analyze(std::move(Input), Options, ClangLibrary, AnalysisDatabase);
	if (!LifecycleSource.empty())
	{
		Model.LifecycleSource = fs::canonical(LifecycleSource);
		for (const std::string Name : LifecycleClasses)
		{
			Model.Dependencies.insert(fs::canonical(Model.LifecycleSource / (Name + ".h")));
		}
	}
	Model.Dependencies.insert(ContextFile);
	for (const auto& [Owner, File] : Model.Input.HostContexts)
	{
		Model.Dependencies.insert(File);
	}
	Emit(std::move(Model), OutputDirectory);
}
